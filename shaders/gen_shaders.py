#!/usr/bin/env python3
"""Compile psp.vert/psp.frag to SPIR-V and regenerate src/vk_shaders.h.

The header is committed so that building psprecomp does not require a GLSL
compiler. Re-run this after editing either shader:

    python3 psprecomp/shaders/gen_shaders.py

Requires glslangValidator or glslc (package glslang).
"""
import pathlib
import shutil
import tempfile
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "vk_shaders.h"


def compile_glsl(src: pathlib.Path, stage: str, dst: pathlib.Path) -> None:
    if shutil.which("glslc"):
        cmd = ["glslc", f"-fshader-stage={stage}", "--target-env=vulkan1.0", str(src), "-o", str(dst)]
    elif shutil.which("glslangValidator"):
        cmd = ["glslangValidator", "-V", "--target-env", "vulkan1.0", str(src), "-o", str(dst)]
    else:
        sys.exit("error: need glslc or glslangValidator (pacman -S glslang)")
    subprocess.run(cmd, check=True)


def words(path: pathlib.Path) -> list[int]:
    data = path.read_bytes()
    if len(data) % 4:
        sys.exit(f"error: {path} is not a whole number of words")
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def emit(name: str, ws: list[int], out: list[str]) -> None:
    out.append(f"static const uint32_t {name}[] = {{")
    for i in range(0, len(ws), 4):
        out.append(",".join(f"0x{w:08x}" for w in ws[i:i + 4]) + ",")
    out.append("};")
    out.append("")


def main() -> None:
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="psp-shaders-"))
    vert, frag = tmp / "psp.vert.spv", tmp / "psp.frag.spv"
    compile_glsl(HERE / "psp.vert", "vertex", vert)
    compile_glsl(HERE / "psp.frag", "fragment", frag)

    out = ["/* Precompiled SPIR-V shaders for psprecomp Vulkan backend.",
           " * Generated by psprecomp/shaders/gen_shaders.py from psp.vert/psp.frag.",
           " * Do not edit by hand. */",
           "#ifndef PSPRECOMP_VK_SHADERS_H",
           "#define PSPRECOMP_VK_SHADERS_H",
           "",
           "#include <stdint.h>",
           ""]
    emit("g_vk_vert_spv", words(vert), out)
    emit("g_vk_frag_spv", words(frag), out)
    out.append("#endif")

    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
